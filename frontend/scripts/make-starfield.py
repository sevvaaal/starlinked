"""Generates src/components/starfield.css: three layers of tiny square stars
drifting upward at different speeds (a parallax night sky).

Technique adapted from a Uiverse.io starfield by sinful_9361 (MIT). Positions
are random but seeded, so re-running the script gives the same sky.

    python3 scripts/make-starfield.py
"""

import random
from pathlib import Path

TILE = 2000  # each layer is a 2000x2000 tile, repeated once below itself
# (size px, star count, seconds per full loop, opacity)
LAYERS = [(1, 360, 120, 0.7), (2, 110, 200, 0.75), (3, 45, 300, 0.85)]
# Mostly cream, with a sprinkle of the site's accent colors.
COLORS = ["#f8f3e8"] * 8 + ["#f8e7a6", "#f3a4c6", "#b7da9e", "#cac5ee"]

rng = random.Random(20261118)
blocks = []
for index, (size, count, seconds, opacity) in enumerate(LAYERS, start=1):
    shadows = ",".join(
        f"{rng.randrange(TILE)}px {rng.randrange(TILE)}px {rng.choice(COLORS)}" for _ in range(count)
    )
    blocks.append(
        f""".starfield-layer--{index} {{
  width: {size}px;
  height: {size}px;
  opacity: {opacity};
  box-shadow: {shadows};
  animation-duration: {seconds}s;
}}
.starfield-layer--{index}::after {{
  width: {size}px;
  height: {size}px;
  box-shadow: inherit;
}}
"""
    )

css = f"""/* Generated by scripts/make-starfield.py — edit the script, not this file. */
.starfield {{
  position: fixed;
  inset: 0;
  z-index: 0;
  overflow: hidden;
  pointer-events: none;
}}

.starfield-layer {{
  position: absolute;
  top: 0;
  left: 0;
  background: transparent;
  animation: starfield-drift linear infinite;
}}

/* A copy of the same tile right below, so the loop is seamless */
.starfield-layer::after {{
  content: '';
  position: absolute;
  top: {TILE}px;
  left: 0;
}}

@keyframes starfield-drift {{
  to {{
    transform: translateY(-{TILE}px);
  }}
}}

@media (prefers-reduced-motion: reduce) {{
  .starfield-layer {{
    animation: none;
  }}
}}

{"".join(blocks)}"""
out = Path(__file__).resolve().parent.parent / "src" / "components" / "starfield.css"
out.write_text(css)
print(f"wrote {out} ({len(css) // 1024} kB)")
